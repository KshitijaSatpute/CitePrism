"""The workspace repository contract shared by the SQLite and PostgreSQL stores.

Phase 3 shipped a single SQLite implementation. Phase 4 keeps that implementation
for one-workstation development and adds a PostgreSQL implementation for the
durable multi-process runtime. Both satisfy this protocol, so the application
service, the API and the workers never branch on the backend.
"""

from __future__ import annotations

from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class WorkspaceRepository(Protocol):
    """Operational state: portfolio, queue, human decisions and activity."""

    # -- manuscripts ---------------------------------------------------
    def upsert_manuscript(self, tenant_id: str, **fields: Any) -> tuple[dict, bool]: ...
    def list_manuscripts(self, tenant_id: str) -> list[dict]: ...
    def get_manuscript(self, tenant_id: str, manuscript_id: str) -> dict: ...
    def update_manuscript_title(self, tenant_id: str, manuscript_id: str, title: str) -> None: ...

    # -- audits and jobs -----------------------------------------------
    def create_audit_job(
        self, tenant_id: str, manuscript_id: str, request: dict, actor_id: str
    ) -> tuple[dict, dict]: ...
    def get_audit(self, tenant_id: str, audit_id: str) -> dict: ...
    def list_audits(self, tenant_id: str, manuscript_id: str) -> list[dict]: ...
    def get_job(self, tenant_id: str, job_id: str) -> dict: ...
    def list_queued_jobs(self) -> list[dict]: ...
    def claim_job(self, tenant_id: str, job_id: str, worker_id: str) -> dict | None: ...
    def update_job_progress(
        self, tenant_id: str, job_id: str, progress: int, stage: str
    ) -> bool: ...
    def job_cancel_requested(self, tenant_id: str, job_id: str) -> bool: ...
    def request_cancel(self, tenant_id: str, job_id: str, actor_id: str) -> dict: ...
    def finish_job(self, tenant_id: str, job_id: str, *, success: bool, **fields: Any) -> None: ...
    def retry_job(self, tenant_id: str, job_id: str, actor_id: str) -> tuple[dict, dict]: ...
    def recover_interrupted_jobs(self) -> int: ...

    # -- durable queue (Phase 4) ---------------------------------------
    def lease_next_job(self, worker_id: str, *, lease_seconds: int) -> dict | None: ...
    def heartbeat_job(self, tenant_id: str, job_id: str, worker_id: str, *,
                      lease_seconds: int) -> bool: ...
    def release_job(self, tenant_id: str, job_id: str, worker_id: str, *,
                    error_code: str | None = None, error_message: str | None = None,
                    backoff_seconds: float = 0.0, max_attempts: int = 3) -> str: ...
    def reclaim_expired_leases(self) -> int: ...
    def queue_depth(self, tenant_id: str | None = None) -> dict: ...

    # -- human workflow -------------------------------------------------
    def latest_decisions(self, tenant_id: str, audit_id: str) -> dict[str, dict]: ...
    def record_decision(self, tenant_id: str, audit_id: str, finding_id: str, disposition: str,
                        rationale: str, reviewer_id: str, idempotency_key: str,
                        expected_current_id: str | None = None) -> dict: ...
    def record_correction(self, tenant_id: str, audit_id: str, **fields: Any) -> dict: ...
    def transition_correction(self, tenant_id: str, correction_id: str, state: str,
                              rationale: str, actor_id: str) -> dict: ...
    def list_corrections(self, tenant_id: str, audit_id: str) -> list[dict]: ...

    # -- activity --------------------------------------------------------
    def list_activity(self, tenant_id: str, audit_id: str | None = None,
                      limit: int = 100) -> list[dict]: ...
    def verify_activity_chain(self, tenant_id: str) -> dict: ...
    def list_review_cases(self, tenant_id: str, **filters: Any) -> list[dict]: ...


@runtime_checkable
class OrganizationRepository(Protocol):
    """Organizations, memberships and reviewer assignment (Phase 4)."""

    def ensure_organization(self, tenant_id: str, name: str, *, actor_id: str = "system") -> dict: ...
    def get_organization(self, tenant_id: str) -> dict | None: ...
    def upsert_member(self, tenant_id: str, subject: str, *, display_name: str | None,
                      email: str | None, roles: list[str], actor_id: str) -> dict: ...
    def list_members(self, tenant_id: str) -> list[dict]: ...
    def deactivate_member(self, tenant_id: str, subject: str, actor_id: str) -> dict: ...
    def assign_case(self, tenant_id: str, audit_id: str, finding_id: str, assignee: str, *,
                    actor_id: str, note: str | None = None, due_at: str | None = None) -> dict: ...
    def unassign_case(self, tenant_id: str, audit_id: str, finding_id: str,
                      actor_id: str) -> dict: ...
    def list_assignments(self, tenant_id: str, *, audit_id: str | None = None,
                         assignee: str | None = None) -> list[dict]: ...
    def assignment_workload(self, tenant_id: str) -> list[dict]: ...


@runtime_checkable
class TelemetryRepository(Protocol):
    """Latency, cost and quality observations used by the SLO endpoint."""

    def record_telemetry(self, tenant_id: str, events: list[dict]) -> int: ...
    def telemetry_window(self, tenant_id: str | None, *, hours: int,
                         audit_id: str | None = None) -> list[dict]: ...


@runtime_checkable
class ExportRepository(Protocol):
    """Signed review package metadata."""

    def record_export(self, tenant_id: str, **fields: Any) -> dict: ...
    def get_export(self, tenant_id: str, export_id: str) -> dict: ...
    def list_exports(self, tenant_id: str, audit_id: str | None = None) -> list[dict]: ...


@runtime_checkable
class RepairRepository(Protocol):
    """Automatic repair attempts against known system issues."""

    def record_repair(self, tenant_id: str, **fields: Any) -> dict: ...
    def update_repair(self, tenant_id: str, repair_id: str, **fields: Any) -> dict: ...
    def list_repairs(self, tenant_id: str, audit_id: str | None = None) -> list[dict]: ...
    def get_repair(self, tenant_id: str, repair_id: str) -> dict: ...


__all__ = [
    "ExportRepository",
    "OrganizationRepository",
    "RepairRepository",
    "TelemetryRepository",
    "WorkspaceRepository",
]
