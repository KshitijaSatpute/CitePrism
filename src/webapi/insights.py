"""Projections for the literature-search and author-overlap views.

Both features existed in the Streamlit diagnostics but had no API, so the React
workspace could not show them. These functions read a stored artifact and return
plain, serializable structures — no model calls, no new provider traffic.

The framing matters as much as the data. Search candidates are unverified leads,
and author overlap is a descriptive observation, not an accusation. Both payloads
carry that language so a client cannot render them as verdicts by accident.
"""

from __future__ import annotations

import re
import unicodedata
from collections import Counter, defaultdict


def normalize_name(value: str | None) -> str:
    """Surname-oriented normalization for overlap counting."""
    text = str(value or "").strip()
    if not text:
        return ""
    if "," in text:
        text = text.split(",", 1)[0]
    else:
        parts = re.findall(r"[^\W\d_]+", text, re.UNICODE)
        text = parts[-1] if parts else ""
    folded = unicodedata.normalize("NFKD", text).casefold()
    return "".join(character for character in folded if character.isalnum())


def display_name(value) -> str:
    if isinstance(value, dict):
        return str(value.get("display_name") or value.get("name") or "").strip()
    return str(value or "").strip()


def missing_citations(artifact: dict) -> dict:
    """Possibly missing literature: co-citation evidence plus verified model leads.

    Co-citation candidates come from the citation graph of the manuscript's own
    resolved references, so every one is a real, indexed record. Model leads
    are shown with the outcome of resolving them against the scholarly indexes.
    """
    payload = _raw_search_leads(artifact)
    gaps = artifact.get("literature_gap_analysis") or {}
    verified = {item["id"]: item for item in gaps.get("suggestions") or [] if item.get("id")}
    for item in payload["items"]:
        check = verified.get(item["id"])
        if check:
            item["verification_status"] = check["verification_status"]
            item["matched_record"] = check.get("matched_record")
            item["already_cited"] = item["already_cited"] or bool(check.get("already_cited"))
    cocitation = gaps.get("cocitation") or {}
    payload["cocitation"] = {
        "status": cocitation.get("status") or ("not_run" if not gaps else gaps.get("status")),
        "references_with_graph": cocitation.get("references_with_graph", 0),
        "min_support": cocitation.get("min_support"),
        "candidates": cocitation.get("candidates", []),
    }
    payload["counts"] = gaps.get("counts", {})
    payload["analysis_status"] = gaps.get("status", "not_run")
    payload["limitations"] = gaps.get("limitations", [])
    payload["available"] = bool(payload["items"] or payload["cocitation"]["candidates"])
    payload["guidance"] = (
        "Co-citation candidates are real works that several of this manuscript's own "
        "references cite. Model leads are shown with whether a real record matches them; "
        "a lead with no matching record may not exist and must never be cited unchecked."
    )
    return payload


def _raw_search_leads(artifact: dict) -> dict:
    """Model-generated literature-search leads, before verification."""
    candidates = artifact.get("missing_citations") or []
    metadata = artifact.get("literature_search_metadata") or {}
    cited_titles = {
        str((reference.get("original_data") or {}).get("parsed", {}).get("title") or "").casefold()
        for reference in artifact.get("scored_references", [])
    }
    items = []
    for index, candidate in enumerate(candidates):
        if not isinstance(candidate, dict) or not candidate.get("title"):
            continue
        title = str(candidate["title"])
        items.append(
            {
                "id": f"candidate-{index + 1}",
                "title": title,
                "authors": str(candidate.get("authors") or "Unknown"),
                "year": str(candidate.get("year") or "Unknown"),
                "rationale": str(candidate.get("rationale") or ""),
                "verification_status": str(
                    candidate.get("verification_status") or "unverified_model_suggestion"
                ),
                "already_cited": title.casefold() in cited_titles,
                "search_url": (
                    "https://openalex.org/works?search="
                    + re.sub(r"\s+", "+", title.strip())[:300]
                ),
            }
        )
    return {
        "available": bool(items),
        "generated": bool(metadata),
        "items": items,
        "metadata": {
            "provider": metadata.get("provider"),
            "model": metadata.get("model"),
            "method_version": metadata.get("method_version"),
            "generated_at": metadata.get("generated_at"),
        },
        "guidance": (
            "These are search leads generated by a language model. A candidate "
            "may not exist, may be misattributed, or may be irrelevant. Resolve "
            "each one against a trusted scholarly index before citing it."
        ),
        "not_a_claim": (
            "Nothing here asserts that the manuscript omitted a required citation."
        ),
    }


def author_overlap(artifact: dict, *, minimum_shared: int = 1) -> dict:
    """Describe repeated author surnames between the manuscript and its references."""
    manuscript = artifact.get("manuscript_metadata") or artifact.get("metadata") or {}
    manuscript_authors = [display_name(item) for item in (manuscript.get("authors") or [])]
    manuscript_keys = {normalize_name(name) for name in manuscript_authors}
    manuscript_keys.discard("")

    nodes: dict[str, dict] = {}
    edges: list[dict] = []
    surname_counts: Counter[str] = Counter()
    label_for: dict[str, str] = {}
    references_by_author: dict[str, list[str]] = defaultdict(list)

    for name in manuscript_authors:
        key = normalize_name(name)
        if key:
            label_for.setdefault(key, name)
            nodes[key] = {
                "id": key,
                "label": name,
                "group": "manuscript_author",
                "reference_count": 0,
            }

    self_citations = 0
    for reference in artifact.get("scored_references", []):
        parsed = (reference.get("original_data") or {}).get("parsed", {}) or {}
        marker = str(reference.get("ref_id") or "")
        authors = parsed.get("authors") or []
        if not authors:
            authors = (reference.get("external_metadata") or {}).get("authors") or []
        keys = set()
        for item in authors:
            name = display_name(item)
            key = normalize_name(name)
            if not key:
                continue
            keys.add(key)
            label_for.setdefault(key, name)
            references_by_author[key].append(marker)
        surname_counts.update(keys)
        shared = keys & manuscript_keys
        if shared:
            self_citations += 1
            for key in shared:
                edges.append(
                    {
                        "author_id": key,
                        "author": label_for.get(key, key),
                        "reference": marker,
                        "kind": "manuscript_author_appears_in_reference",
                    }
                )

    for key, count in surname_counts.items():
        if count < minimum_shared and key not in nodes:
            continue
        node = nodes.setdefault(
            key,
            {
                "id": key,
                "label": label_for.get(key, key),
                "group": "reference_author",
                "reference_count": 0,
            },
        )
        node["reference_count"] = count
        node["references"] = sorted(set(references_by_author.get(key, [])))[:25]

    total_references = len(artifact.get("scored_references", []))
    repeated = sorted(
        (node for node in nodes.values() if node.get("reference_count", 0) >= 2),
        key=lambda node: (-node["reference_count"], node["label"]),
    )

    analysis = artifact.get("self_citation_analysis") or {}
    tiers = []
    for reference in artifact.get("scored_references", []):
        record = reference.get("self_citation") or {}
        if record.get("tier") and record.get("tier") != "none":
            tiers.append({
                "reference": str(reference.get("ref_id") or ""),
                "tier": record["tier"],
                "counted": bool(record.get("is_self_citation")),
                "matches": record.get("matches", []),
                "questionable_reasons": record.get("questionable_reasons", []),
            })
    return {
        "available": bool(nodes),
        "self_citation": {
            "method_version": analysis.get("method_version"),
            "counts": analysis.get("counts", {}),
            "patterns": analysis.get("patterns", []),
            "questionable": analysis.get("questionable", []),
            "by_author": analysis.get("by_author", {}),
            "orcids": analysis.get("orcids", {}),
            "thresholds": analysis.get("thresholds", {}),
            "references": tiers,
            "identity_note": analysis.get("identity_note"),
        } if analysis else None,
        "manuscript_authors": manuscript_authors,
        "nodes": sorted(nodes.values(), key=lambda node: (-node["reference_count"], node["label"])),
        "edges": edges,
        "repeated_authors": repeated[:50],
        "counts": {
            "total_references": total_references,
            "references_sharing_a_manuscript_author": self_citations,
            "distinct_reference_authors": len(
                [node for node in nodes.values() if node["group"] == "reference_author"]
            ),
            "share_of_references": (
                round(self_citations / total_references, 4) if total_references else 0.0
            ),
        },
        "method": "surname_normalization_v1",
        "guidance": (
            "Self-citations are matched by ORCID iD where available, otherwise by surname and "
            "first initial; surname-only matches are shown but not counted. The repeated-author "
            "chart groups by surname alone, so different people who share a surname appear "
            "together there. Self-citation is a normal and often necessary scholarly practice."
        ),
        "not_a_claim": (
            "This view describes name repetition only. It does not measure bias, "
            "coercive citation, or misconduct, and it must not be reported as such."
        ),
    }


__all__ = ["author_overlap", "display_name", "missing_citations", "normalize_name"]
