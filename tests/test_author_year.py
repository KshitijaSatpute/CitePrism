class ChapterTests(unittest.TestCase):
    def test_chapters_are_detected_with_their_authors(self):
        from src.workspace.parts import detect_parts
        structure = detect_parts(VOLUME)
        self.assertTrue(structure["multi_part"])
        parts = [(p["page_start"], p["page_end"], p["authors"], p["references"]) for p in structure["parts"]]
        self.assertEqual(parts, [(2, 4, ["Anna Meier", "Jonas Weber"], 5),
                                 (5, 6, ["Lena Fischer-Hall", "Tom Berger"], 7)])

    def test_a_chapter_becomes_its_own_pdf(self):
        import io
        import pypdf
        from src.workspace.parts import part_pdf, part_title
        reader = pypdf.PdfReader(io.BytesIO(part_pdf(VOLUME, 5, 6)))
        self.assertEqual(len(reader.pages), 2)
        self.assertEqual(part_title("Lehren und Lernen", {"number": 2, "title": "Feedback that works",
                                                           "page_start": 5, "page_end": 6}),
                         "2. Feedback that works — Lehren und Lernen")
        self.assertEqual(part_title("HOCHSCHULLEHRE IM DIGITALEN ZEITALTER: Theorie und Praxis",
                                    {"number": 1, "title": "", "page_start": 1, "page_end": 21}),
                         "1. Opening pages (pp. 1–21) — Hochschullehre im Digitalen Zeitalter")
        from src.workspace.parts import part_filename
        self.assertEqual(part_filename("1791374559866_Buch_Hochschullehre_im_Digitalen_Zeitalter.pdf",
                                       {"number": 3, "page_start": 40, "page_end": 59}),
                         "Buch_Hochschullehre_im_Digitalen_Zeitalter_ch03_p40-59.pdf")

    def test_front_matter_without_a_model(self):
        source = pdf_source(VOLUME)
        self.assertEqual(front_matter(source)["authors"], ["Anna Meier", "Jonas Weber"])
        chapter = {**source, "pages": source["pages"][4:6], "document_info": {}}
        guess = front_matter(chapter)
        self.assertEqual(guess["authors"], ["Lena Fischer-Hall", "Tom Berger"])
        self.assertTrue(guess["title"].startswith("Feedback that works"))


class ReviewTests(unittest.TestCase):
    def review(self, data):
        from src.evidence.review import build_review
        return build_review(data)

    def artifact(self):
        result = anchored()
        references = []
        for ref in result["references_list"]:
            key = ref["ref_id"].lower().replace(" ", "")
            count = sum(key in o["reference_keys"] for o in result["citations_in_text"])
            references.append({"reference_uid": ref["reference_uid"], "ref_id": ref["ref_id"], "original_data": ref,
                               "resolution": {"status": "resolved"}, "external_metadata": {"doi": "10.1/x"},
                               "citation_count": count, "evidence_status": "not_assessed",
                               "claim_assessment": "not_assessed", "claim_assessments": []})
        return {"schema_version": SCHEMA_VERSION, "extraction_metadata": result["extraction_metadata"],
                "citations_in_text": result["citations_in_text"], "scored_references": references}

    def test_year_conflicts_and_multiple_lists_reach_the_reviewer(self):
        review = self.review(self.artifact())
        categories = [f["category"] for f in review["findings"]]
        self.assertIn("multiple_reference_lists", categories)
        conflict = next(f for f in review["findings"] if f["category"] == "citation_year_mismatch")
        self.assertIn("Siebert, 2005", conflict["explanation"])
        self.assertIn("2015", conflict["explanation"])
        self.assertNotIn("extraction_reliability", categories)

    def test_an_unreadable_document_is_flagged_first_and_summarised_honestly(self):
        from src.assistant import AuditAssistant
        data = self.artifact()
        for ref in data["scored_references"]:
            ref["original_data"] = {**ref["original_data"], "extraction_status": "needs_review"}
            ref["resolution"] = {"status": "not_found"}
            ref["citation_count"] = 0
        review = self.review(data)
        self.assertEqual(review["findings"][0]["category"], "extraction_reliability")
        self.assertEqual(review["findings"][0]["priority"], "high")
        summary = AuditAssistant(review).summary()
        self.assertIn("could not read this document reliably", summary["text"])


class DegradedParseTests(unittest.TestCase):
    def test_rule_based_parse_only_for_author_year_documents(self):
        from src.evidence.providers import ProviderFailure
        from src.extractors.gemini_extractor import GeminiExtractor
        extractor = object.__new__(GeminiExtractor)
        failure = ProviderFailure("service_unavailable", "google", tried=["google:a", "google:b"])
        source = pdf_source(VOLUME)
        text, _ = joined_source(source)
        parsed = extractor._deterministic_parse(text, source, failure)
        self.assertEqual(parsed["extraction_metadata"]["degraded"]["reason"], "service_unavailable")
        self.assertEqual(parsed["metadata"]["authors"], ["Anna Meier", "Jonas Weber"])
        numbered = pdf_source(NUMBERED)
        self.assertIsNone(extractor._deterministic_parse(joined_source(numbered)[0], numbered, failure))


