def anchored(path=VOLUME):
    return anchor_manuscript({"metadata": {}, "citations_in_text": [], "references_list": []}, pdf_source(path))


class EntryReadingTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        text, _ = joined_source(pdf_source(VOLUME))
        cls.sections = bib.find_sections(text)

    def test_every_reference_list_is_found_in_any_language(self):
        self.assertEqual([section.heading for section in self.sections], ["Literatur", "References"])
        self.assertEqual([len(section.entries) for section in self.sections], [5, 7])

    def test_a_figure_list_after_the_bibliography_is_not_an_entry(self):
        self.assertFalse(any("ABB." in entry.raw for section in self.sections for entry in section.entries))

    def test_capitalised_names_are_read_and_written_normally(self):
        hattie = self.sections[0].entries[0]
        self.assertEqual(hattie.authors, ["Hattie, J.", "Timperley, H."])
        self.assertEqual(hattie.year, "2007")
        self.assertEqual(hattie.doi, "10.3102/003465430298487")
        self.assertTrue(hattie.title.startswith("The power of feedback"))

    def test_undated_organisation_in_a_subsection(self):
        stiftung = self.sections[0].entries[-1]
        self.assertEqual(stiftung.organization, "Stiftung Hochschullehre")
        self.assertEqual(stiftung.year_status, "no_date")
        self.assertEqual(stiftung.subsection, "Internetquellen")

    def test_year_suffixes_and_hyphenated_names(self):
        labels = bib.labels_for(self.sections[1].entries)
        self.assertIn("Fischer-Hall 2024a", labels)
        self.assertIn("Fischer-Hall 2024b", labels)

    def test_parse_entry_variants(self):
        cases = {
            "BLUME, D. & FLAGMEIER D. (i.E.). Von Praxis zu Methodik. Weinheim: Beltz.": ("in_press", None),
            "UNIVERSITÄT WIEN (08.2017). Peer-Feedback. Abgerufen am 16. März 2025.": ("dated", "2017"),
            "PETERS, JONATHAN (2022, 27. Juli). Animals learn through play. Blog.": ("dated", "2022"),
            "FEIXAS, M., ZELLWEGER, F ., & FLEPP , G. (2020). Degrees of reflection. Journal, 1, 2–3.": ("dated", "2020"),
        }
        for raw, (status, year) in cases.items():
            with self.subTest(raw=raw[:30]):
                entry = bib.parse_entry(bib.Entry(raw=raw, start=0, end=len(raw)), raw)
                self.assertEqual((entry.year_status, entry.year), (status, year))
        peters = bib.parse_entry(bib.Entry(raw="", start=0, end=0), list(cases)[2])
        self.assertEqual(peters.authors, ["Peters, Jonathan"])
        feixas = bib.parse_entry(bib.Entry(raw="", start=0, end=0), list(cases)[3])
        self.assertEqual([name.split(",")[0] for name in feixas.authors], ["Feixas", "Zellweger", "Flepp"])


class CitationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.result = anchored()
        cls.markers = {o["marker"]: o for o in cls.result["citations_in_text"]}

    def test_footnote_citations_point_at_the_superscript_in_the_sentence(self):
        footnote = self.markers["Wenger, 1998; Meier, 2021 (footnote 1)"]
        window = footnote["context_window"]
        self.assertEqual(window[footnote["target_marker_start"]:footnote["target_marker_end"]], "1")
        self.assertIn("Fachbereichen.1", window)
        self.assertEqual(footnote["reference_keys"], ["wenger1998·ch.1", "meier2021·ch.1"])

    def test_parenthetical_narrative_and_et_al_citations(self):
        for marker in ("Hattie & Timperley, 2007", "Fischer-Hall (2024a)", "Fischer-Hall, 2024b", "Kolb, 1984",
                       "Berger et al. (2022)", "Carless and Boud (2018)"):
            self.assertIn(marker, self.markers)

    def test_each_chapter_cites_only_its_own_list(self):
        hattie = [o for o in self.result["citations_in_text"] if "Hattie" in o["marker"]]
        self.assertEqual(sorted(key for o in hattie for key in o["reference_keys"]),
                         ["hattie2007·ch.1", "hattie2007·ch.2"])

    def test_co_authors_are_not_separate_citations(self):
        self.assertFalse(any(marker.startswith(("Timperley", "Boud")) for marker in self.markers))

    def test_undated_citation_links_to_the_undated_entry(self):
        self.assertEqual(self.markers["Stiftung Hochschullehre, o. J. (footnote 4)"]["reference_keys"],
                         ["stiftunghochschullehreo.j.·ch.1"])

    def test_a_citation_year_that_disagrees_with_the_list_is_recorded(self):
        siebert = next(r for r in self.result["references_list"] if r["ref_id"].startswith("Siebert"))
        self.assertEqual(siebert["citation_year_mismatches"][0]["cited_year"], "2005")
        self.assertEqual(siebert["citation_year_mismatches"][0]["listed_year"], "2015")

    def test_only_the_genuinely_uncited_entry_is_uncited(self):
        cited = {key for o in self.result["citations_in_text"] for key in o["reference_keys"]}
        uncited = [r["ref_id"] for r in self.result["references_list"]
                   if r["ref_id"].lower().replace(" ", "") not in cited]
        self.assertEqual(uncited, ["Unused 2019 · ch. 2"])

    def test_capital_runs_do_not_cause_catastrophic_backtracking(self):
        entries = [bib.parse_entry(bib.Entry(raw="", start=0, end=0), "LERNFÖRDERLICHES, A. (2020). Title here.")]
        text = "LERNFÖRDERLICHES FEEDBACK IN DER HOCHSCHULLEHRE " * 200
        started = time.perf_counter()
        bib.find_citations(text, 0, len(text), entries, ["x"])
        self.assertLess(time.perf_counter() - started, 2.0)


