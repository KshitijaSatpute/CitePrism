"""Regenerate src/assistant/lexicon.py from a hunspell dictionary.

    python scripts/make_lexicon.py /usr/share/hunspell/en_US.dic

Lists every real word (with its -s/-ed/-ing forms) that the assistant's spelling
corrector would otherwise rewrite into one of its vocabulary words, so it is left
alone. Run it after changing `VOCABULARY` or the correction rules.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

# Real words that are nearly always a misspelling here, and stay corrected.
STILL_CORRECTED = {"summery"}


def dictionary_words(path: Path) -> set[str]:
    words = set()
    for line in path.read_text(encoding="utf-8", errors="ignore").splitlines()[1:]:
        word, _, flags = line.partition("/")
        word = word.strip()
        if not (word.isalpha() and word.islower()):
            continue
        words.add(word)
        if "S" in flags:
            words.add(word + ("es" if word.endswith(("s", "x", "ch", "sh")) else "s"))
        if "D" in flags:
            words.add(word + ("d" if word.endswith("e") else "ed"))
        if "G" in flags:
            words.add((word[:-1] if word.endswith("e") else word) + "ing")
    return words


def main() -> int:
    path = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/hunspell/en_US.dic")
    import src.assistant.lexicon as lexicon
    lexicon.REAL_WORDS = frozenset()              # measure the rules alone
    import src.assistant.understanding as understanding
    understanding.REAL_WORDS = frozenset()
    changed = sorted(word for word in dictionary_words(path)
                     if understanding.correct_spelling(word) != word and word not in STILL_CORRECTED)
    rows, row = [], "    "
    for word in changed:
        item = f'"{word}", '
        if len(row) + len(item) > 116:
            rows.append(row.rstrip())
            row = "    "
        row += item
    rows.append(row.rstrip())
    target = ROOT / "src" / "assistant" / "lexicon.py"
    target.write_text(
        '"""Real English words the spelling corrector must leave alone.\n\n'
        'The corrector (`understanding.correct_spelling`) fixes misspellings of CitePrism\'s\n'
        'vocabulary ("refrences" -> "references"). A real word one or two letters away from\n'
        'a vocabulary word ("messing", "discussed", "retort") must not be rewritten, or\n'
        '"I\'m messing this up" would become a question about missing literature.\n\n'
        'Generated by scripts/make_lexicon.py from the hunspell en_US dictionary; do not edit.\n'
        '"""\n\nREAL_WORDS: frozenset[str] = frozenset({\n' + "\n".join(rows) + "\n})\n", encoding="utf-8")
    print(f"{len(changed)} protected words written to {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
