#!/usr/bin/env python
"""Create a blank, blind annotation sheet from scored artifacts.

    python scripts/make_annotation_template.py \
        --artifacts data/scored --domain "computer science" \
        --annotator janvi --output data/evaluation/annotate_batch1.jsonl

Each line identifies one reference and shows the annotator what they need to
judge it — the printed entry and every citing sentence — and leaves every label
empty. System predictions are deliberately omitted: an annotator who can see
the model's answer anchors on it, and the evaluation stops measuring anything.

Fill in any subset of: identity_label, support_label, relevance_label,
metadata_label, is_self_citation, extraction_label, should_be_reviewed.
Then run scripts/run_evaluation.py on the completed file.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))


def template_rows(artifact: dict, *, domain: str | None, annotator: str) -> list[dict]:
    digest = (artifact.get("source_document") or {}).get("pdf_sha256")
    if not digest:
        return []
    manuscript = artifact.get("manuscript_metadata") or {}
    rows = []
    for reference in artifact.get("scored_references", []):
        original = reference.get("original_data") or {}
        marker = str(reference.get("ref_id"))
        rows.append({
            "item_id": f"{digest[:12]}-{marker.strip('[]')}",
            "manuscript_sha256": digest,
            "reference_marker": marker,
            "reference_title": (original.get("parsed") or {}).get("title"),
            "domain": domain,
            "annotator": annotator,
            # Labels — fill in what you can judge; leave the rest null.
            "identity_label": None,
            "support_label": None,
            "relevance_label": None,
            "metadata_label": None,
            "is_self_citation": None,
            "extraction_label": None,
            "should_be_reviewed": None,
            "notes": None,
            # Context for the annotator (ignored by the evaluator).
            "context": {
                "manuscript_title": manuscript.get("title"),
                "manuscript_authors": manuscript.get("authors"),
                "printed_entry": original.get("raw_text"),
                "citing_sentences": [c.get("context_window") for c in reference.get("citation_occurrences", [])][:5],
            },
        })
    return rows


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Create a blind CitePrism annotation template")
    parser.add_argument("--artifacts", required=True, help="scored artifact file or directory")
    parser.add_argument("--output", required=True, help="JSONL file to write")
    parser.add_argument("--domain", default=None, help="research field of these manuscripts")
    parser.add_argument("--annotator", default="unassigned")
    arguments = parser.parse_args(argv)

    source = Path(arguments.artifacts)
    paths = sorted(source.glob("*.json")) if source.is_dir() else [source]
    rows = []
    for path in paths:
        try:
            artifact = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            print(f"skipping unreadable {path}")
            continue
        rows.extend(template_rows(artifact, domain=arguments.domain, annotator=arguments.annotator))
    if not rows:
        print("No scored artifacts with a source document were found.")
        return 1
    output = Path(arguments.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    header = {"schema_version": "citeprism-eval-v1", "name": output.stem,
              "description": "Blind annotation template generated by CitePrism. Labels are human judgements."}
    output.write_text("\n".join(json.dumps(row, ensure_ascii=False) for row in [header, *rows]) + "\n",
                      encoding="utf-8")
    print(f"Wrote {len(rows)} items to {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
